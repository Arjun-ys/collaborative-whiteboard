const { test } = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const { once } = require('node:events');
const { mkdtempSync, writeFileSync, mkdirSync, rmSync } = require('node:fs');
const { tmpdir } = require('node:os');
const path = require('node:path');
const { createApp } = require('../dist/app');
const { allowedOriginsFromEnv, permittedWsOrigin, validRoomPath } = require('../dist/services/connectionPolicy');

test('production serves the compiled client and health responds to database readiness', async () => {
  const directory = mkdtempSync(path.join(tmpdir(), 'whiteboard-http-test-'));
  writeFileSync(path.join(directory, 'index.html'), '<html>Whiteboard</html>');
  mkdirSync(path.join(directory, 'assets'));
  writeFileSync(path.join(directory, 'assets', 'app.js'), 'console.log("app")');
  let ready = true;
  const server = http.createServer(createApp({ clientDirectory: directory, isDatabaseReady: () => ready, pendingRooms: () => 1, allowedOrigins: [] }));
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  try {
    const response = await fetch(base);
    assert.equal(response.status, 200);
    assert.equal(await response.text(), '<html>Whiteboard</html>');
    const asset = await fetch(`${base}/assets/app.js`);
    assert.match(asset.headers.get('cache-control'), /immutable/);
    assert.equal((await fetch(`${base}/health`)).status, 200);
    ready = false;
    assert.equal((await fetch(`${base}/health`)).status, 503);
  } finally {
    await new Promise(resolve => server.close(resolve));
    // This path was generated by this test, inside the OS temporary directory.
    rmSync(directory, { recursive: true, force: true });
  }
});

test('WebSocket policy accepts same-host and configured browser origins only', () => {
  const allowed = allowedOriginsFromEnv('https://demo.example.com,http://localhost:5173');
  assert.equal(permittedWsOrigin({ headers: { host: 'localhost:5001', origin: 'http://localhost:5001' } }, allowed), true);
  assert.equal(permittedWsOrigin({ headers: { host: 'localhost:5001', origin: 'http://localhost:5173' } }, allowed), true);
  assert.equal(permittedWsOrigin({ headers: { host: 'localhost:5001', origin: 'https://other.example.com' } }, allowed), false);
  assert.equal(permittedWsOrigin({ headers: { host: 'localhost:5001', origin: 'null' } }, allowed), false);
  assert.equal(permittedWsOrigin({ headers: { host: 'localhost:5001' } }, allowed), true);
  assert.throws(() => allowedOriginsFromEnv('https://example.com/path'));
  assert.equal(validRoomPath('/health'), false);
  assert.equal(validRoomPath('/valid-room'), true);
  assert.equal(validRoomPath('/bad/room'), false);
});
